def training_curve(train_txt):
    ep = re.findall(r"epoch\s+(\d+)/\d+\s+train mse=([\d.]+)\s+val mse=([\d.]+)", open(train_txt).read())
    e = np.array([int(x[0]) for x in ep])
    tr = np.array([float(x[1]) for x in ep])
    va = np.array([float(x[2]) for x in ep])
    fig, ax = plt.subplots(figsize=(6.5, 2.9))
    ax.plot(e, tr, color=BLUE, marker="o", ms=3, label="training MSE")
    ax.plot(e, va, color=ORANGE, marker="s", ms=3, label="validation MSE")
    ax.axhline(0.2647, color=GREY, ls="--", lw=1, label="no-change forecast (0.265)")
    ax.set_xlabel("epoch")
    ax.set_ylabel("MSE (normalised deltas)")
    ax.set_ylim(0, 0.3)
    ax.legend(fontsize=7.5, frameon=False)
    ax.set_title("LSTM training (lstm.py, 22,560 windows, hidden = 32)", fontsize=9)
    save(fig, "A_training_curve.png")


def classifier_lead():
    from common import PRESSURE_CRITICAL_THRESHOLD, WIND_CRITICAL_THRESHOLD
    from edge_ai import HISTORY, QOS_MODEL_PATH, QoSClassifier, trend_features
    from ocean_model import CycloneParams, OceanNode
    clf = QoSClassifier.load(QOS_MODEL_PATH)
    tr = np.array(OceanNode(CycloneParams(onset_step=10, speed_km_per_step=8, closest_km=30), seed=4).trace(110))
    prob = [float(clf.predict_proba(trend_features(tr[max(0, t - HISTORY + 1):t + 1]))[0]) for t in range(len(tr))]
    rule = (tr[:, 0] >= WIND_CRITICAL_THRESHOLD) | (tr[:, 2] <= PRESSURE_CRITICAL_THRESHOLD)
    first_rule = int(np.argmax(rule))
    first_ml = int(np.argmax(np.array(prob) >= 0.5))
    fig, ax = plt.subplots(figsize=(7, 3.0))
    ax.plot(prob, color=BLUE, lw=1.5, label="ML probability (edge_ai.QoSClassifier)")
    ax.step(range(len(rule)), rule.astype(float), color=RED, lw=1.2, where="post", label="rule says CRITICAL")
    ax.axhline(0.5, color=BLUE, ls=":", lw=1)
    ax.axvline(first_ml, color=BLUE, ls="--", lw=0.8)
    ax.axvline(first_rule, color=RED, ls="--", lw=0.8)
    ax.annotate("", xy=(first_rule, 0.62), xytext=(first_ml, 0.62),
                arrowprops=dict(arrowstyle="<->", color="black", lw=1))
    ax.text((first_ml + first_rule) / 2, 0.66, f"{first_rule - first_ml} readings earlier", ha="center", fontsize=8)
    ax.set_xlabel("reading number")
    ax.set_ylabel("probability / flag")
    ax.set_ylim(-0.05, 1.1)
    ax.legend(fontsize=7.5, frameon=False, loc="upper left")
    ax.set_title("Early warning: ML flags the approaching storm before the threshold rule", fontsize=9)
    save(fig, "A_classifier_lead.png")
    return first_rule - first_ml


def gateway_waits(demo_txt):
    s = open(demo_txt).read()
    s = s[s.index('"policy"'):]
    vals = {}
    for cls in ("CRITICAL", "NORMAL", "NON_ESSENTIAL"):
        m = re.search(rf'"{cls}": \{{.*?"avg_wait_ms": ([\d.]+),\s*"p95_wait_ms": ([\d.]+)', s, re.S)
        vals[cls] = (float(m.group(1)), float(m.group(2)))
    fig, ax = plt.subplots(figsize=(6.2, 2.8))
    x = np.arange(3)
    ax.bar(x - 0.18, [vals[c][0] for c in vals], 0.36, color=BLUE, label="average wait")
    ax.bar(x + 0.18, [vals[c][1] for c in vals], 0.36, color=ORANGE, label="95th-percentile wait")
    for i, c in enumerate(vals):
        ax.text(i + 0.18, vals[c][1] * 1.15, f"{vals[c][1]:.0f}", ha="center", fontsize=7.5)
    ax.set_yscale("log")
    ax.set_xticks(x, list(vals))
    ax.set_ylabel("wait at gateway (ms, log)")
    ax.legend(fontsize=7.5, frameon=False)
    ax.set_title("Gateway queue waits per class during the live run (1200 B/s backbone)", fontsize=9)
    save(fig, "A_gateway_waits.png")
    return vals


