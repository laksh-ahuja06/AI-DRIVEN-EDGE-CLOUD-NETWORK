def satellite_bands():
    from edge_ai import IR_SCALE
    from satellite_station import SyntheticImager
    img = SyntheticImager(size=384, seed=7).frame(0.9, (0.5, 0.5), rotation=1.1)
    names = ["Visible", "Infrared", "Water vapour", "Near-IR"]
    fig, axes = plt.subplots(1, 4, figsize=(7.5, 2.3))
    for k, ax in enumerate(axes):
        band = img[k].astype(float)
        if k in (1, 2):
            band = -band / IR_SCALE  # cold clouds shown bright
        ax.imshow(band, cmap="gray")
        ax.set_title(names[k], fontsize=8.5)
        ax.axis("off")
    fig.suptitle("One synthetic 4-band, 16-bit frame (satellite_station.SyntheticImager, intensity 0.9)",
                 fontsize=9)
    save(fig, "S_satellite_bands.png")


def loss_pattern():
    import random
    from ocean_model import GilbertElliottLink
    n = 200
    ge = GilbertElliottLink(0.15, burstiness=0.7, seed=3)
    g = np.array([ge.lost() for _ in range(n)])
    r = random.Random(3)
    ind = np.array([r.random() < 0.15 for _ in range(n)])
    fig, axes = plt.subplots(2, 1, figsize=(7, 1.9), sharex=True)
    for ax, arr, lab in ((axes[0], ind, f"independent loss (15%): {ind.mean():.0%} lost"),
                         (axes[1], g, f"Gilbert-Elliott bursty loss (15%, burst 0.7): {g.mean():.0%} lost")):
        ax.bar(np.arange(n), arr.astype(int), width=1.0, color=RED)
        ax.set_yticks([])
        ax.set_ylabel(lab, rotation=0, ha="left", va="center", fontsize=7.5, labelpad=0)
        ax.yaxis.set_label_coords(0.0, 1.25)
        ax.spines["left"].set_visible(False)
    axes[1].set_xlabel("packet sequence number (red = lost)")
    save(fig, "S_loss_pattern.png")


def truth_vs_recon():
    from reconstruction import Reconstructor, linear_fill
    rows = list(csv.DictReader(open(os.path.join(REPO, "logs", "truth_BUOY_07.csv"))))
    vals = np.array([[float(r["wind"]), float(r["temp"]), float(r["pressure"])] for r in rows])
    lost = np.array([r["lost"] == "1" for r in rows])
    rec = Reconstructor("lstm")
    repaired = vals.copy()
    est_l, est_s, idx = [], [], []
    t = 0
    while t < len(vals):
        if not lost[t]:
            t += 1
            continue
        s = t
        while t < len(vals) and lost[t]:
            t += 1
        if t >= len(vals) or s == 0:
            break
        n = t - s
        f = rec.fill_gap(list(repaired[:s]), vals[t], n)
        lin = linear_fill(vals[s - 1], vals[t], n)
        repaired[s:t] = f
        idx += list(range(s, t))
        est_l += list(f[:, 2])
        est_s += list(lin[:, 2])
    idx = np.array(idx)
    fig, ax = plt.subplots(figsize=(7, 3.0))
    ax.plot(vals[:, 2], color=GREY, lw=1.2, label="true pressure (sensor truth log)")
    ax.scatter(idx, vals[idx, 2], marker="x", color="black", s=28, label="lost readings (truth)", zorder=4)
    ax.scatter(idx, est_l, facecolor="none", edgecolor=ORANGE, s=40, lw=1.4, label="LSTM estimate", zorder=5)
    ax.set_xlabel("sequence number (BUOY_07, live run)")
    ax.set_ylabel("pressure (hPa)")
    ax.legend(fontsize=7.5, frameon=False, loc="lower left")
    ax.set_title("Reconstruction of packets really lost during the live run", fontsize=9)
    save(fig, "S_truth_vs_recon.png")
    err_l = np.abs(np.array(est_l) - vals[idx, 2]).mean()
    err_s = np.abs(np.array(est_s) - vals[idx, 2]).mean()
    return len(idx), int(lost.sum()), len(vals), round(float(err_l), 3), round(float(err_s), 3)


