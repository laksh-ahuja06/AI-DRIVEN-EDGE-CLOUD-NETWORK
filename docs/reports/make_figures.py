def ocean_trace():
    from ocean_model import CycloneParams, OceanNode
    tr = np.array(OceanNode(CycloneParams(onset_step=15, speed_km_per_step=10, closest_km=25), seed=1).trace(140))
    fig, ax = plt.subplots(figsize=(7, 3.1))
    ax.plot(tr[:, 0], color=BLUE, lw=1.4, label="wind (km/h)")
    ax.axhline(60, color=BLUE, ls=":", lw=1)
    ax.set_xlabel("reading number (1 per second)")
    ax.set_ylabel("wind (km/h)", color=BLUE)
    ax2 = ax.twinx()
    ax2.plot(tr[:, 2], color=GREEN, lw=1.4, label="pressure (hPa)")
    ax2.axhline(990, color=GREEN, ls=":", lw=1)
    ax2.set_ylabel("pressure (hPa)", color=GREEN)
    ax2.spines["top"].set_visible(False)
    ax.axvline(15, color=GREY, lw=0.8, ls="--")
    ax.text(16, ax.get_ylim()[1] * 0.92, "cyclone onset", fontsize=8, color=GREY)
    ax.set_title("Cyclone passage generated by ocean_model.py (dotted = critical thresholds)", fontsize=9)
    save(fig, "L_ocean_trace.png")


def demo_timeline(demo_txt):
    rows = re.findall(r"\[\s*(\d+)s\] risk=\s*([\d.]+) alert=(\w+)\s+rx=(\d+) reconstructed=(\d+) "
                      r"concealed=(\d+) critical=(\d+)", open(demo_txt).read())
    t, risk, alert, rx, rec, conc, crit = (np.array([r[i] for r in rows]) for i in range(7))
    t, risk = t.astype(int), risk.astype(float)
    fig, ax = plt.subplots(figsize=(7, 3.0))
    ax.plot(t, risk, color=RED, marker="o", ms=3.5, lw=1.5, label="fused risk")
    ax.axhline(60, color=RED, ls=":", lw=1)
    ax.fill_between(t, 0, 100, where=alert == "True", color=RED, alpha=0.08, label="alert active")
    ax.set_ylim(0, 105)
    ax.set_xlabel("time since start (s)")
    ax.set_ylabel("fused risk (0-100)")
    ax2 = ax.twinx()
    ax2.plot(t, rec.astype(int), color=ORANGE, lw=1.3, ls="--", label="reconstructed (cum.)")
    ax2.plot(t, crit.astype(int), color=BLUE, lw=1.3, ls="-.", label="critical packets (cum.)")
    ax2.set_ylabel("packet count")
    ax2.spines["top"].set_visible(False)
    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, fontsize=7.5, loc="upper left", frameon=False)
    ax.set_title("Live run (run_demo.py, 75 s): risk, alert and packet counters from /predict and /status", fontsize=9)
    save(fig, "L_demo_timeline.png")


